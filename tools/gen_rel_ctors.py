#!/usr/bin/env python3
"""Writes rel_ctors.cpp: for each actor module, where the linker put its
static constructors (tools/rel_cc.py), and tww_rel_run_ctors(name), which
DynamicModuleControl::do_link calls.

  gen_rel_ctors.py <out.cpp> <module names...>
"""
import sys

def main():
    out, names = sys.argv[1], sys.argv[2:]
    with open(out, "w") as fp:
        fp.write("// Generated by tools/gen_rel_ctors.py -- do not edit.\n")
        fp.write("#include <string.h>\n\n")
        fp.write("typedef void (*tww_ctor)(void);\n")
        for n in names:
            fp.write('extern "C" tww_ctor __start_tww_ctors_%s[] __attribute__((weak, visibility("hidden")));\n' % n)
            fp.write('extern "C" tww_ctor __stop_tww_ctors_%s[] __attribute__((weak, visibility("hidden")));\n' % n)
        fp.write("\nstruct tww_rel_ctors { const char* name; tww_ctor* start; tww_ctor* stop; bool done; };\n")
        fp.write("static tww_rel_ctors s_rels[] = {\n")
        for n in names:
            fp.write('    {"%s", __start_tww_ctors_%s, __stop_tww_ctors_%s, false},\n' % (n, n, n))
        fp.write("};\n\n")
        fp.write('''// Runs a module's static constructors, once (DynamicModuleControl::do_link).
// Returns 0 if the name is no actor module.
extern "C" int tww_rel_run_ctors(const char* name)
{
    for (unsigned i = 0; i < sizeof(s_rels) / sizeof(s_rels[0]); i++) {
        tww_rel_ctors& r = s_rels[i];
        if (strcmp(r.name, name) != 0)
            continue;
        if (!r.done) {
            r.done = true;
            if (r.start)
                for (tww_ctor* c = r.start; c < r.stop; c++)
                    if (*c)
                        (*c)();
        }
        return 1;
    }
    return 0;
}
''')

if __name__ == "__main__":
    main()
