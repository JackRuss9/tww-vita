#!/usr/bin/env python3
"""Lists the Wind Waker decomp's game and JSystem sources for the port's
CMake (written as a CMake file), from the object list in tww/configure.py.

Every object of the retail game is listed: the matching ones, and the
non-matching ones too (they have C++ for most of their functions; the
functions still empty, "/* Nonmatching */", are listed separately in
stubs.txt so the port can keep those actors from spawning).

Left out: the Dolphin SDK, MSL, the runtime, the debugger (TRK, OdemuExi2,
amcstubs, odenotstub) and the REL loader's per-module code: the port's
platform layer (sms-port/platform) and the host C library replace them.
Debug-only objects (DEBUG_ONLY) are left out too.

  gen_sources.py <tww dir> <out.cmake> [stubs.txt]
"""
import json, os, re, sys

SKIP_LIBS = {
    # Dolphin SDK (the platform layer implements it)
    "base", "os", "exi", "si", "db", "mtx", "dvd", "vi", "pad", "ai", "ar",
    "dsp", "card", "hio", "gx", "gd", "gba",
    # Metrowerks runtime, C library and debugger
    "Runtime.PPCEABI.H", "MSL_C", "TRK_MINNOW_DOLPHIN", "amcstubs",
    "OdemuExi2", "odenotstub",
    # REL loader glue (_prolog/_epilog per module); the modules are linked
    # into the program instead
    "REL",
    # host I/O to the development kit
    "JHostIO",
}

def parse(configure_py):
    """(lib, status expression, path) for every Object/ActorRel."""
    src = open(configure_py, encoding="utf-8").read()
    i = src.find("config.libs = [")
    if i >= 0:
        src = src[i:]
    libre = re.compile(r'(?:DolphinLib|JSystemLib|Rel)\(\s*"([^"]+)"|"lib":\s*"([^"]+)"|\b(Object|ActorRel)\(')
    lib = None
    out = []
    pos = 0
    while True:
        m = libre.search(src, pos)
        if not m:
            break
        pos = m.end()
        if m.group(1) or m.group(2):
            lib = m.group(1) or m.group(2)
            continue
        # the status: everything up to the first comma outside parentheses
        d = 0
        j = pos
        while j < len(src):
            ch = src[j]
            if ch == "(":
                d += 1
            elif ch == ")":
                if d == 0:
                    break
                d -= 1
            elif ch == "," and d == 0:
                break
            j += 1
        status = src[pos:j].strip()
        pm = re.match(r',\s*f?"([^"]+)"', src[j:])
        if not pm:
            continue
        path = pm.group(1)
        if m.group(3) == "ActorRel":
            out.append(("actor:" + path, status, "d/actor/%s.cpp" % path))
        else:
            out.append((lib, status, path))
    return out

HDR = re.compile(r'/\*\s*([0-9A-Fa-f]{8})-([0-9A-Fa-f]{8})\s+\.text\s+(\S+)\s*\*/')

def stubs_in(path):
    """Functions whose body is only a comment (still to be decompiled)."""
    t = open(path, errors="ignore").read()
    res = []
    for m in HDR.finditer(t):
        size = int(m.group(2), 16) - int(m.group(1), 16)
        i = t.find("{", m.end())
        semi = t.find(";", m.end())
        if i < 0 or (0 <= semi < i):
            continue
        d = 0
        for j in range(i, len(t)):
            if t[j] == "{":
                d += 1
            elif t[j] == "}":
                d -= 1
                if d == 0:
                    break
        body = re.sub(r'/\*.*?\*/|//[^\n]*', '', t[i + 1:j], flags=re.S).strip()
        if body == "" and size > 8:
            res.append((m.group(3), size))
    return res

def main():
    tww, out = sys.argv[1], sys.argv[2]
    stubs_out = sys.argv[3] if len(sys.argv) > 3 else None
    objs = parse(os.path.join(tww, "configure.py"))
    cxx, c, actors, rels = [], [], [], []
    stub_lines = []
    for lib, status, path in objs:
        if lib in SKIP_LIBS:
            continue
        # debug-only objects, except the output stream retail code uses
        if status == "DEBUG_ONLY" and not path.endswith("JSUOutputStream.cpp"):
            continue
        f = os.path.join(tww, "src", path)
        if not os.path.exists(f):
            continue
        if lib.startswith("actor:"):
            actors.append(lib[6:])
            rels.append(f)
        else:
            (c if f.endswith(".c") else cxx).append(f)
        if not (status == "Matching" or (status.startswith("MatchingFor") and "GZLE01" in status)):
            st = stubs_in(f)
            if st:
                total = sum(s for _, s in st)
                stub_lines.append("%s\t%d\t%d\t%s" % (path, len(st), total,
                                  " ".join(n for n, _ in st)))
    with open(out, "w") as fp:
        fp.write("# Generated by tools/gen_sources.py from tww/configure.py\n")
        fp.write("set(TWW_CXX_SOURCES\n")
        for f in cxx:
            fp.write("  %s\n" % f)
        fp.write(")\nset(TWW_C_SOURCES\n")
        for f in c:
            fp.write("  %s\n" % f)
        fp.write(")\n")
        fp.write("# The actor modules (RELs on the disc): their start-up code is run\n"
                 "# when the game links the module (tools/rel_cc.py, rel_ctors)\n")
        fp.write("set(TWW_REL_SOURCES\n")
        for f in rels:
            fp.write("  %s\n" % f)
        fp.write(")\nset(TWW_REL_NAMES\n")
        for a in actors:
            fp.write("  %s\n" % a)
        fp.write(")\n")
    if stubs_out:
        with open(stubs_out, "w") as fp:
            fp.write("# file\tempty functions\tbytes\tnames\n")
            fp.write("\n".join(stub_lines) + "\n")
    print("gen_sources: %d C++ and %d C files (%d actor modules); %d files with empty functions"
          % (len(cxx), len(c), len(actors), len(stub_lines)))

if __name__ == "__main__":
    main()
